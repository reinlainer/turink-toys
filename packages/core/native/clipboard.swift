// Keeps images that pass through the clipboard and puts them back on it.
//
// Node has no way to learn that the clipboard changed short of reading it over
// and over, and reading the contents is what newer macOS asks the person about.
// The change counter can be checked freely, so this helper watches the counter
// and reads the contents only when it moves and an image is on offer.
//
// Usage: clipboard watch --dir <folder>   keep running, save each new image into
//                                         the folder and print one JSON line per
//                                         event: { event: "ready" }, { event:
//                                         "saved", path }; exits when the process
//                                         that started it does
//        clipboard save --dir <folder>    save the image on the clipboard now and
//                                         print { saved, duplicate, reason }
//        clipboard copy <file>...         put the images back on the clipboard
//                                         and print { copied }
//        clipboard --version              print VERSION and exit
//
// Saved files are named <yyyyMMdd-HHmmss>-<hash>.<ext>, the hash being the
// first twelve hex digits of the file's SHA-256. An image whose hash is already
// in the folder is not saved again.

import AppKit
import CryptoKit
import Foundation

let VERSION = "1.0.0"

// Put on everything this helper writes, so the watcher does not keep an image
// the person copied back out of the gallery a second time.
let MARKER = NSPasteboard.PasteboardType("toys.turink.app.clipboard.archived")

// Markers from nspasteboard.org that password managers and similar apps set on
// content that should not be kept, plus our own.
let SKIP: [NSPasteboard.PasteboardType] = [
  MARKER,
  NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
  NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
  NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
]

let JPEG = NSPasteboard.PasteboardType("public.jpeg")

let args = Array(CommandLine.arguments.dropFirst())

func emit(_ object: [String: Any]) {
  guard let data = try? JSONSerialization.data(withJSONObject: object, options: [.sortedKeys]),
    let text = String(data: data, encoding: .utf8)
  else { return }
  print(text)
  fflush(stdout)
}

func fatal(_ message: String) -> Never {
  FileHandle.standardError.write(Data((message + "\n").utf8))
  exit(2)
}

func option(_ name: String) -> String? {
  guard let index = args.firstIndex(of: name), index + 1 < args.count else { return nil }
  return args[index + 1]
}

// Why the clipboard holds nothing to keep, or nil when it holds an image.
// Copying a file in Finder offers its icon as an image beside the file itself,
// so anything carrying a file reference is a file, not a picture.
func refusal(_ board: NSPasteboard) -> String? {
  let types = board.types ?? []
  if types.contains(where: { SKIP.contains($0) }) { return "skipped" }
  if types.contains(.fileURL) { return "file" }
  if types.contains(.png) || types.contains(.tiff) || types.contains(JPEG) { return nil }
  return "no-image"
}

// The image as it will be stored. PNG and JPEG are kept as they arrive; TIFF,
// which screenshots and older apps offer uncompressed, is stored as PNG.
func imageData(_ board: NSPasteboard) -> (Data, String)? {
  if let png = board.data(forType: .png) { return (png, "png") }
  if let jpeg = board.data(forType: JPEG) { return (jpeg, "jpg") }
  if let tiff = board.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff),
    let png = rep.representation(using: .png, properties: [:])
  {
    return (png, "png")
  }
  return nil
}

func shortHash(_ data: Data) -> String {
  SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined().prefix(12).lowercased()
}

let stamp: DateFormatter = {
  let formatter = DateFormatter()
  formatter.locale = Locale(identifier: "en_US_POSIX")
  formatter.dateFormat = "yyyyMMdd-HHmmss"
  return formatter
}()

func alreadyKept(_ folder: URL, _ hash: String) -> Bool {
  let names = (try? FileManager.default.contentsOfDirectory(atPath: folder.path)) ?? []
  return names.contains { $0.contains("-\(hash).") }
}

// Saves whatever image the clipboard holds. Returns the JSON reported for it.
func keep(_ board: NSPasteboard, into folder: URL) -> [String: Any] {
  if let reason = refusal(board) { return ["saved": NSNull(), "duplicate": false, "reason": reason] }
  guard let (data, ext) = imageData(board) else {
    return ["saved": NSNull(), "duplicate": false, "reason": "unreadable"]
  }
  let hash = shortHash(data)
  do {
    try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
  } catch {
    return ["saved": NSNull(), "duplicate": false, "reason": "folder", "message": error.localizedDescription]
  }
  if alreadyKept(folder, hash) { return ["saved": NSNull(), "duplicate": true, "reason": "duplicate"] }
  let file = folder.appendingPathComponent("\(stamp.string(from: Date()))-\(hash).\(ext)")
  do {
    try data.write(to: file, options: .atomic)
  } catch {
    return ["saved": NSNull(), "duplicate": false, "reason": "write", "message": error.localizedDescription]
  }
  return ["saved": file.path, "duplicate": false, "reason": NSNull()]
}

func folderArgument() -> URL {
  guard let dir = option("--dir") else { fatal("--dir <folder> is required") }
  return URL(fileURLWithPath: (dir as NSString).expandingTildeInPath)
}

// The counter is checked twice a second. What was on the clipboard when the
// watch began is left alone: turning collection on should not file away
// something copied before.
func watch() -> Never {
  let folder = folderArgument()
  let board = NSPasteboard.general
  let parent = getppid()
  var seen = board.changeCount
  emit(["event": "ready", "version": VERSION])

  let timer = Timer(timeInterval: 0.5, repeats: true) { _ in
    // Started by the app, the helper goes when the app goes, even if the app
    // never got the chance to stop it.
    if getppid() != parent { exit(0) }
    let count = board.changeCount
    if count == seen { return }
    seen = count
    let outcome = keep(board, into: folder)
    if let saved = outcome["saved"] as? String {
      emit(["event": "saved", "path": saved])
    } else if let reason = outcome["reason"] as? String, reason == "folder" || reason == "write" {
      emit(["event": "error", "reason": reason, "message": outcome["message"] ?? ""])
    }
  }
  RunLoop.main.add(timer, forMode: .common)
  RunLoop.main.run()
  exit(0)
}

// Each image goes on as its own item, so pasting several where several are
// accepted gives them all. The data is written now rather than promised, so
// nothing depends on this process staying alive after it exits.
func copy(_ paths: [String]) -> Never {
  var items: [NSPasteboardItem] = []
  var missing: [String] = []
  for path in paths {
    let url = URL(fileURLWithPath: path)
    guard let data = try? Data(contentsOf: url) else {
      missing.append(path)
      continue
    }
    let item = NSPasteboardItem()
    switch url.pathExtension.lowercased() {
    case "png": item.setData(data, forType: .png)
    case "jpg", "jpeg": item.setData(data, forType: JPEG)
    default:
      guard let rep = NSBitmapImageRep(data: data), let png = rep.representation(using: .png, properties: [:]) else {
        missing.append(path)
        continue
      }
      item.setData(png, forType: .png)
    }
    item.setData(Data("1".utf8), forType: MARKER)
    items.append(item)
  }
  if items.isEmpty {
    emit(["copied": 0, "missing": missing])
    exit(1)
  }
  let board = NSPasteboard.general
  board.clearContents()
  let ok = board.writeObjects(items)
  emit(["copied": ok ? items.count : 0, "missing": missing])
  exit(ok ? 0 : 1)
}

switch args.first {
case "--version":
  print(VERSION)
case "watch":
  watch()
case "save":
  emit(keep(NSPasteboard.general, into: folderArgument()))
case "copy":
  let paths = Array(args.dropFirst())
  if paths.isEmpty { fatal("copy needs at least one file") }
  copy(paths)
default:
  fatal("usage: clipboard watch --dir <folder> | save --dir <folder> | copy <file>... | --version")
}
